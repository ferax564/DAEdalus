#!/usr/bin/env python3
"""Rewrite the roadmap's remaining-failures table from a conformance JSON.

The committed baseline is docs/conformance/msl-4.1.0.json. The table names every
model that does not pass, split into runs that do not finish and runs that
finish but differ. Markers in docs/roadmap.md bound the generated section.

    python3 tools/roadmap_failures.py [--check] [json] [roadmap]
"""

import argparse
import json
import sys


START = "<!-- conformance-failures:start -->"
END = "<!-- conformance-failures:end -->"


def clip(s, n=160):
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1] + "…"


def detail(row):
    if row.get("status") == "differ":
        bad = [f["signal"] for f in row.get("failed", [])]
        bad += [s + " (missing)" for s in row.get("missing", [])]
        n = row.get("signals")
        head = ", ".join(bad[:4])
        if len(bad) > 4:
            head += " …"
        text = f"{len(bad)}/{n} signals: {head}" if n else head
        return clip(text)
    err = (row.get("error") or "").removeprefix("error: ")
    return clip(err).replace("|", "\\|")


def render(data):
    results = data["results"]
    summary = data["summary"]
    unfinished = [r for r in results if r.get("status") in ("error", "timeout")]
    differs = [r for r in results if r.get("status") == "differ"]
    unfinished.sort(key=lambda r: (r.get("status") != "error", r["model"]))
    differs.sort(key=lambda r: r["model"])
    total = summary.get("total", len(results))
    passed = summary.get("pass", 0)
    finished = total - summary.get("error", 0) - summary.get("timeout", 0)
    lines = [
        START,
        "",
        f"**{finished} of {total}** example models run to the end and **{passed}** match the reference",
        f"results. The {len(unfinished) + len(differs)} that do not are listed from",
        "`docs/conformance/msl-4.1.0.json` (regenerated by `tools/roadmap_failures.py`).",
        "",
        f"### Does not finish ({len(unfinished)})",
        "",
        "Translation or simulation stopped, or the run hit the wall-clock limit.",
        "",
        "| Model | Status | Detail |",
        "| --- | --- | --- |",
    ]
    for r in unfinished:
        lines.append(f"| `{r['model']}` | {r.get('status')} | {detail(r)} |")
    lines += [
        "",
        f"### Finishes but differs ({len(differs)})",
        "",
        "The run completed and at least one comparison signal left the reference tube.",
        "Several of these are a single signal.",
        "",
        "| Model | Signals outside the tube |",
        "| --- | --- |",
    ]
    for r in differs:
        lines.append(f"| `{r['model']}` | {detail(r)} |")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("json_path", nargs="?", default="docs/conformance/msl-4.1.0.json")
    ap.add_argument("roadmap", nargs="?", default="docs/roadmap.md")
    ap.add_argument("--check", action="store_true", help="exit 1 if the roadmap section is stale")
    args = ap.parse_args()
    with open(args.json_path, encoding="utf-8") as f:
        data = json.load(f)
    block = render(data)
    with open(args.roadmap, encoding="utf-8") as f:
        text = f.read()
    if START not in text or END not in text:
        sys.exit(f"{args.roadmap} is missing the {START} markers")
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    # post begins with whatever followed the end marker; block already includes both markers.
    updated = pre + block + post.lstrip("\n")
    if updated == text:
        print(f"{args.roadmap} matches {args.json_path}")
        return
    if args.check:
        sys.exit(f"{args.roadmap} does not match {args.json_path}; run tools/roadmap_failures.py")
    with open(args.roadmap, "w", encoding="utf-8") as f:
        f.write(updated)
    print(f"updated {args.roadmap}")


if __name__ == "__main__":
    main()
